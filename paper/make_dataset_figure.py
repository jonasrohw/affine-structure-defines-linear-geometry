svg = []
def add(s): svg.append(s)
def rect(x,y,w,h,fill,stroke="none",sw=1,rx=0,extra=""):
    add(f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" rx="{rx:g}" fill="{fill}" stroke="{stroke}" stroke-width="{sw:g}" {extra}/>')
def line(x1,y1,x2,y2,color=None,sw=1.4,dash=None):
    add(f'<path d="M{x1:g},{y1:g} L{x2:g},{y2:g}" fill="none" stroke="{color or C["line"]}" stroke-width="{sw:g}"'+(f' stroke-dasharray="{dash}"' if dash else '')+'/>')
def path(d,color,sw=1.6,dash=None,arrow=False,opacity=1):
    add(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{sw:g}" opacity="{opacity}"'+(f' stroke-dasharray="{dash}"' if dash else '')+(f' marker-end="url(#{"red" if color==C["red"] else "blue" if color==C["blue"] else "gray"}-arrow)"' if arrow else '')+'/>')
def text(x,y,s,size=20,color=None,weight=400,anchor="start",family="DejaVu Sans",extra=""):
    add(f'<text x="{x:g}" y="{y:g}" font-family="{family}" font-size="{size}" font-weight="{weight}" fill="{color or C["ink"]}" text-anchor="{anchor}" {extra}>{escape(s)}</text>')
def circle(x,y,r,fill,stroke="none",sw=1.5):
    add(f'<circle cx="{x:g}" cy="{y:g}" r="{r:g}" fill="{fill}" stroke="{stroke}" stroke-width="{sw:g}"/>')
def arrow(x,y,x2,y2,color=None,sw=1.8):
    path(f'M{x},{y} L{x2},{y2}',color or C['muted'],sw,arrow=True)
def step(x,y,n,s):
    text(x,y,n,17,C['muted'],650)
    text(x+32,y,s,20,C['ink'],600)
def chip(x,y,w,s,color,bg):
    rect(x,y,w,27,bg,rx=4)
    text(x+w/2,y+19,s,17,color,600,"middle")
def sub(s): return str(s).translate(str.maketrans('0123456789','₀₁₂₃₄₅₆₇₈₉'))
def tokenline(x,y,items,size=19):
    # Actual sentence order; colored answer tokens are not additional symbols.
    for label,color in items:
        text(x,y,label,size,color,family='DejaVu Sans Mono')
        x += len(label)*size*.602 + 12

