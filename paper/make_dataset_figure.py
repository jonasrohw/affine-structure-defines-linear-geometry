def pair_table(x,y,r,color,pale):
    cell=30
    for col,i in enumerate(shown):
        text(x+(col+.5)*cell,y-10,'s'+sub(i),16,color if col==1 else C['muted'],650 if col==1 else 400,'middle')
    for row,s in enumerate(shown):
        text(x-10,y+(row+.5)*cell+5,'s'+sub(s),16,color if row==0 else C['muted'],650 if row==0 else 400,'end')
        for col,o in enumerate(shown):
            v=bool(lookup.labels[r,s,o])
            rect(x+col*cell,y+row*cell,cell,cell,color if v else pale,C['white'],.7)
            text(x+(col+.5)*cell,y+(row+.5)*cell+6,'y' if v else 'n',18,C['white'] if v else color,500,'middle')
    rect(x+cell+2,y+2,cell-4,cell-4,'none',C['ink'],2.2,3)
    # Repeat the highlighted pair as a readable lookup, without crossing cells.
    text(x+17,y+6*cell+28,'s₀, s₁ →',19,color,600)
    chip(x+113,y+6*cell+8,34,'y' if r==0 else 'n',color,pale)

